/**
 * 根据错误码获取用户友好提示。
 * @param code 业务错误码 (来自 R.code 或 StreamChunk.error_code)
 * @param fallback 后端返回的原始 msg (作为兜底, 仅当 code 未命中映射时使用)
 * @returns 面向用户的提示文本
 */
export function getErrorMessage(code: number | null | undefined, fallback?: string): string {
  if (code != null && errorCodeMap[code]) {
    return errorCodeMap[code]
  }
  return fallback || '操作失败，请稍后重试'
}
